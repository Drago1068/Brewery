    runtime_id = uuid.uuid4()
    source = _source(
        additions=(
            SourceAddition(
                id=never_id,
                ingredient_id=uuid.uuid4(),
                amount=Decimal("1"),
                unit="g",
                use_stage="MASH",
                timing_minutes=0,
            ),
            SourceAddition(
                id=planned_id,
                ingredient_id=uuid.uuid4(),
                amount=Decimal("2"),
                unit="g",
                use_stage="MASH",
                timing_minutes=0,
            ),
            SourceAddition(
                id=runtime_id,
                ingredient_id=uuid.uuid4(),
                amount=Decimal("3"),
                unit="g",
                use_stage="MASH",
                timing_minutes=0,
            ),
        )
    )
