# P3-AC-032 tracked artifact scan: candidate paths come from Git's tracked-file
# index (`git ls-files -z`) so untracked residue generated by this very suite
# (e.g. apps/api/.test-brewing.db) can never fail the assertion.
FORBIDDEN_TRACKED_SUFFIXES = (
    ".db",
    ".db-journal",
    ".db-shm",
    ".db-wal",
    ".dump",
    ".jsonl",
    ".journal",
    ".key",
    ".log",
    ".pem",
    ".sqlite",
    ".sqlite-journal",
    ".sqlite-shm",
    ".sqlite-wal",
    ".trace",
)
FORBIDDEN_TRACKED_NAMES = frozenset({".env", ".test-brewing.db", ".test-brewing-p3rr.db"})
FORBIDDEN_TRACKED_FRAGMENTS = (
    "/.idea/",
    "/.next/",
    "/.vscode/",
    "/__pycache__/",
    "/coverage/",
    "/dist/",
    "/node_modules/",
    "/target/",
    "/traces/",
)


def _tracked_paths(root: Path) -> list[str]:
    """Repo-root-relative tracked paths, safely parsed from `git ls-files -z`."""
    if not (root / ".git").exists() or not shutil.which("git"):
        return []
    listing = subprocess.check_output(
        ["git", "ls-files", "-z"],
        cwd=root,
        text=True,
        encoding="utf-8",
    )
    return [entry for entry in listing.split("\0") if entry]


def _prohibited_tracked_paths(tracked: Sequence[str]) -> list[str]:
    forbidden: list[str] = []
    for rel in tracked:
        normalized = rel.replace("\\", "/")
        name = Path(normalized).name
        if name == ".env" or (name.endswith(".env") and name != ".env.example"):
            forbidden.append(rel)
            continue
        if name in FORBIDDEN_TRACKED_NAMES or name.endswith(FORBIDDEN_TRACKED_SUFFIXES):
            forbidden.append(rel)
            continue
        if any(fragment in f"/{normalized}/" for fragment in FORBIDDEN_TRACKED_FRAGMENTS):
            forbidden.append(rel)
    return forbidden


def _init_git(root: Path, tracked: Sequence[str], untracked: Sequence[str] = ()) -> None:
    subprocess.run(["git", "init", "-q"], cwd=root, check=True)
    subprocess.run(["git", "config", "user.email", "t@example.invalid"], cwd=root, check=True)
    subprocess.run(["git", "config", "user.name", "Test"], cwd=root, check=True)
    for rel in [*tracked, *untracked]:
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("x", encoding="utf-8")
    if tracked:
        subprocess.run(["git", "add", "--", *tracked], cwd=root, check=True)
        subprocess.run(["git", "commit", "-qm", "baseline"], cwd=root, check=True)


